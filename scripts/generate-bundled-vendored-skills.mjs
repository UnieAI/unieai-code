#!/usr/bin/env bun
// Vendors external SKILL.md skill packs into compiled-in bundled skills.
//
// Reads each skill directory (SKILL.md + aux files), parses frontmatter, and
// emits a generated TS module per group under src/skills/bundled/vendored/.
// The generated module inlines name/description/body/files (JSON-encoded, so
// backticks and ${...} in the content are safe) and exports a register fn that
// loops over them calling registerBundledSkill().
//
// Re-run after updating a source pack:
//   bun run scripts/generate-bundled-vendored-skills.mjs
//
// Sources are external (a cloned repo / the local plugin marketplace cache);
// the generated TS is self-contained and committed.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parseYaml } from 'yaml'

const HERE = fileURLToPath(new URL('.', import.meta.url))
const OUT_DIR = join(HERE, '..', 'src', 'skills', 'bundled', 'vendored')
const HOME = process.env.HOME || ''

// Text file extensions worth inlining as skill reference files. Binary assets
// (images, office docs) are skipped — they can't help a prompt-only skill.
const TEXT_EXT = new Set([
  '.md', '.markdown', '.py', '.sh', '.js', '.mjs', '.cjs', '.ts', '.tsx',
  '.json', '.jsonc', '.csv', '.tsv', '.txt', '.yaml', '.yml', '.toml',
  '.html', '.css', '.sql',
])
const MAX_FILE_BYTES = 256 * 1024
const MAX_FILES_PER_SKILL = 40

// Groups to vendor. Each maps a logical group → list of root dirs that contain
// <skill>/SKILL.md children.
const GROUPS = [
  {
    name: 'taste',
    registerFn: 'registerTasteSkills',
    // Only the flagship taste skill; the repo ships several sibling design
    // skills but the request was specifically "taste-skill".
    skillDirs: ['/tmp/taste-skill/skills/taste-skill'],
  },
  {
    name: 'finance',
    registerFn: 'registerFinanceSkills',
    pluginsRoot: join(
      HOME,
      '.claude/plugins/marketplaces/claude-for-financial-services/plugins/vertical-plugins',
    ),
    // All 7 verticals: each vertical has a skills/ dir of <skill>/SKILL.md.
    verticals: [
      'financial-analysis', 'equity-research', 'investment-banking',
      'private-equity', 'wealth-management', 'fund-admin', 'operations',
    ],
  },
]

function walkTextFiles(skillDir) {
  const out = {}
  let count = 0
  const recurse = dir => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const abs = join(dir, entry.name)
      if (entry.isDirectory()) {
        recurse(abs)
        continue
      }
      const rel = relative(skillDir, abs).split(sep).join('/')
      if (rel === 'SKILL.md') continue
      const dot = entry.name.lastIndexOf('.')
      const ext = dot >= 0 ? entry.name.slice(dot).toLowerCase() : ''
      if (!TEXT_EXT.has(ext)) continue
      const size = statSync(abs).size
      if (size > MAX_FILE_BYTES) continue
      if (count >= MAX_FILES_PER_SKILL) continue
      out[rel] = readFileSync(abs, 'utf8')
      count++
    }
  }
  recurse(skillDir)
  return out
}

function parseSkill(skillDir) {
  const skillPath = join(skillDir, 'SKILL.md')
  if (!existsSync(skillPath)) return null
  const raw = readFileSync(skillPath, 'utf8')
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!m) return null
  let fm
  try {
    fm = parseYaml(m[1]) || {}
  } catch {
    return null
  }
  const name = String(fm.name || '').trim()
  const description = String(fm.description || '').trim()
  const body = m[2].trim()
  if (!name || !body) return null
  return { name, description, body, files: walkTextFiles(skillDir) }
}

function collectGroupSkills(group) {
  const dirs = []
  if (group.skillDirs) dirs.push(...group.skillDirs)
  if (group.pluginsRoot && group.verticals) {
    for (const v of group.verticals) {
      const skillsRoot = join(group.pluginsRoot, v, 'skills')
      if (!existsSync(skillsRoot)) continue
      for (const entry of readdirSync(skillsRoot, { withFileTypes: true })) {
        if (entry.isDirectory()) dirs.push(join(skillsRoot, entry.name))
      }
    }
  }
  const skills = []
  const seen = new Set()
  for (const dir of dirs) {
    if (!existsSync(dir)) {
      console.warn(`[skip] missing: ${dir}`)
      continue
    }
    const parsed = parseSkill(dir)
    if (!parsed) {
      console.warn(`[skip] no valid SKILL.md frontmatter/body: ${dir}`)
      continue
    }
    if (seen.has(parsed.name)) {
      console.warn(`[skip] duplicate skill name "${parsed.name}" from ${dir}`)
      continue
    }
    seen.add(parsed.name)
    skills.push(parsed)
  }
  return skills
}

function emitModule(group, skills) {
  const header = `// @generated by scripts/generate-bundled-vendored-skills.mjs — DO NOT EDIT.
// Vendored "${group.name}" skill pack (${skills.length} skills) compiled into the CLI.
import type { ContentBlockParam } from '@anthropic-ai/sdk/resources/index.mjs'
import { registerBundledSkill } from '../../bundledSkills.js'

type VendoredSkill = {
  name: string
  description: string
  body: string
  files: Record<string, string>
}

const SKILLS: VendoredSkill[] = ${JSON.stringify(skills, null, 0)}

export function ${group.registerFn}(): void {
  for (const skill of SKILLS) {
    const hasFiles = Object.keys(skill.files).length > 0
    registerBundledSkill({
      name: skill.name,
      description: skill.description,
      userInvocable: true,
      ...(hasFiles ? { files: skill.files } : {}),
      getPromptForCommand: async (): Promise<ContentBlockParam[]> => [
        { type: 'text', text: skill.body },
      ],
    })
  }
}
`
  const outPath = join(OUT_DIR, `${group.name}.generated.ts`)
  writeFileSync(outPath, header, 'utf8')
  return outPath
}

let total = 0
for (const group of GROUPS) {
  const skills = collectGroupSkills(group)
  const outPath = emitModule(group, skills)
  total += skills.length
  console.log(`[${group.name}] ${skills.length} skills → ${relative(process.cwd(), outPath)}`)
  for (const s of skills) console.log(`    /${s.name}`)
}
console.log(`Done. ${total} vendored skills generated.`)
